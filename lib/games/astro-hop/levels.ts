/**
 * The Astro Hop levels, drawn as text: one string per row, 15 rows, one
 * character per 16×16 tile. Edit a level by editing its rows (every row must
 * be the same length); add one by adding an entry. `npm test` checks that
 * every level is well formed and that the beacon can be reached.
 *
 * Tiles
 *   .  empty              #  ground (rock or cloud, by theme)
 *   X  hard block         B  brick (Big Kit breaks it)
 *   ?  star block: coin   M  star block: Star Seed, or a Comet Berry for Big Kit
 *   L  hidden block with an extra life (invisible until bumped from below)
 *   T  launch tube (2 wide; the rim is drawn on its open end)
 *   _  bridge (jump up through it, stand on top)
 *   C  star coin          F  base of the beacon pole (the goal)
 *   c  checkpoint beacon (respawn here after passing it)
 *
 * Things
 *   K  Kit's start        g  Grumble (walks, falls off ledges)
 *   k  Shellbot (walks, turns at ledges; stomp it into a shell and kick it)
 *   f  Boing the space frog (hops)
 *   HHH  platform moving right and back (as wide as the run of H's)
 *   VVV  platform moving up and back
 */

