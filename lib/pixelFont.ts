const ROWS: Record<string, boolean[][]> = Object.fromEntries(
  Object.entries(GLYPHS).map(([ch, art]) => [
    ch,
    art.split("|").map((row) => [...row].map((c) => c === "#")),
  ]),
);

/** Width of `text` in font pixels (unknown characters count as spaces). */
export function textWidth(text: string): number {
  return text.length === 0 ? 0 : text.length * (GLYPH_W + SPACING) - SPACING;
}

/** Every lit font pixel of `text`, top-left origin. Lowercase is drawn as uppercase. */
export function textPixels(text: string): { x: number; y: number }[] {
  const pixels: { x: number; y: number }[] = [];
  [...text.toUpperCase()].forEach((ch, i) => {
    const rows = ROWS[ch] ?? ROWS[" "];
    const ox = i * (GLYPH_W + SPACING);
    rows.forEach((row, y) =>
      row.forEach((lit, x) => {
        if (lit) pixels.push({ x: ox + x, y });
      }),
    );
  });
  return pixels;
}

export const hasGlyph = (ch: string) => ch.toUpperCase() in GLYPHS;
